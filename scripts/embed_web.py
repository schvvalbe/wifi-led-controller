"""Embed deterministic gzip assets in flash; no uploadfs step or CDN needed."""
from pathlib import Path
import gzip


def generate(root):
    assets = [("INDEX_HTML", "index.html"), ("APP_CSS", "app.css"), ("APP_JS", "app.js"), ("THEME_JS", "theme.js"),
              ("MD5_JS", "md5.js"), ("MANIFEST", "manifest.webmanifest"), ("SERVICE_WORKER", "sw.js"),
              ("ICON_SVG", "icon.svg"), ("ICON_192", "icon-192.png"), ("ICON_512", "icon-512.png"),
              ("ICON_MASKABLE", "icon-maskable.png"), ("APPLE_ICON", "apple-touch-icon.png")]
    lines = ["// Generated by scripts/embed_web.py. Do not edit.", "#pragma once", "#include <Arduino.h>"]
    for symbol, filename in assets:
        data = gzip.compress((root / "web" / filename).read_bytes(), compresslevel=9, mtime=0)
        lines.append(f"const uint8_t {symbol}[] PROGMEM = {{")
        lines.extend(",".join(str(b) for b in data[i:i+24]) + "," for i in range(0, len(data), 24))
        lines.append("};")
    target = root / "include" / "WebAssets.h"
    content = "\n".join(lines) + "\n"
    if not target.exists() or target.read_text() != content:
        target.write_text(content)


if __name__ == "__main__":
    generate(Path(__file__).resolve().parents[1])
else:
    Import("env")
    generate(Path(env.subst("$PROJECT_DIR")))
